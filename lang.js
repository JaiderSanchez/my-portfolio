const botonesIdioma = document.querySelectorAll(".idioma-btn");

function aplicarIdioma(idioma) {
  const textos = traducciones[idioma] || traducciones.es;

  document.querySelectorAll("[data-i18n]").forEach((elemento) => {
    const clave = elemento.dataset.i18n;
    if (Object.hasOwn(textos, clave)) elemento.textContent = textos[clave];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((elemento) => {
    const clave = elemento.dataset.i18nHtml;
    // HTML estático escrito por el desarrollador: nunca introducir datos del usuario aquí.
    if (Object.hasOwn(textos, clave)) elemento.innerHTML = textos[clave];
  });

  ["alt", "aria-label", "content"].forEach((atributo) => {
    const nombreDatos = "i18n" + atributo.split("-").map((parte) =>
      parte.charAt(0).toUpperCase() + parte.slice(1)
    ).join("");

    document.querySelectorAll(`[data-i18n-${atributo}]`).forEach((elemento) => {
      const clave = elemento.dataset[nombreDatos];
      if (Object.hasOwn(textos, clave)) elemento.setAttribute(atributo, textos[clave]);
    });
  });

  const enlaceWhatsApp = document.querySelector("[data-i18n-whatsapp]");
  if (enlaceWhatsApp) {
    const clave = enlaceWhatsApp.dataset.i18nWhatsapp;
    if (Object.hasOwn(textos, clave)) {
      const url = new URL(enlaceWhatsApp.href);
      url.searchParams.set("text", textos[clave]);
      enlaceWhatsApp.href = url.toString();
    }
  }

  document.documentElement.lang = idioma;
  document.title = textos["seo.title"];

  botonesIdioma.forEach((boton) => {
    boton.setAttribute("aria-pressed", String(boton.dataset.lang === idioma));
  });
}

botonesIdioma.forEach((boton) => {
  boton.addEventListener("click", () => {
    const idioma = boton.dataset.lang;
    aplicarIdioma(idioma);
    try {
      localStorage.setItem("portfolio-language", idioma);
    } catch (_) {
      // El cambio funciona incluso si el navegador bloquea el almacenamiento.
    }
  });
});

let idiomaInicial = "es";
try {
  if (localStorage.getItem("portfolio-language") === "en") idiomaInicial = "en";
} catch (_) {}
aplicarIdioma(idiomaInicial);
